_CITY_RE = re.compile(r"^[А-Яа-яЁё][А-Яа-яЁё\s\-]{1,58}$")
_WORD_RE = re.compile(r"[А-Яа-яЁёA-Za-z]+")


def normalize_city(raw: str) -> str:
    text = " ".join((raw or "").split()).strip(" .,;")
    text = re.sub(r"^(?:г\.?|город)\s+", "", text, flags=re.IGNORECASE)
    text = re.sub(r"\s+(?:город)$", "", text, flags=re.IGNORECASE)
    text = re.sub(r"\s*-\s*", "-", text)

    def capitalize(match: re.Match[str]) -> str:
        word = match.group(0)
        if (
            match.start() > 0
            and text[match.start() - 1] == "-"
            and word.lower() in {"на", "по", "за", "из", "под", "над", "и", "в", "во", "у"}
        ):
            return word.lower()
        return word[:1].upper() + word[1:].lower()

    return _WORD_RE.sub(capitalize, text)


def is_valid_city_name(raw: str) -> bool:
    city = normalize_city(raw)
    return bool(city) and bool(_CITY_RE.fullmatch(city))


def is_known_city(raw: str) -> bool:
    return normalize_city(raw).lower() in KNOWN_CITIES


def city_variants(city: str) -> set[str]:
    """Возвращает основы названия города в разных падежных формах."""
    base = normalize_city(city).lower()
    variants: set[str] = {base}

    if base.endswith(("а", "я")):
        stem = base[:-1]
        variants.update(
            {
                stem + "е",
                stem + "ы",
                stem + "и",
                stem + "у",
                stem + "ой",
                stem + "ей",
            }
        )
    elif base.endswith(("ь", "й")):
        stem = base[:-1]
        variants.update({stem + "и", stem + "я", stem + "е", stem + "ю", stem + "ем"})
    elif base.endswith(("о", "е")):
        stem = base[:-1]
        variants.update({stem + "е", stem + "а"})
    else:
        variants.update({base + "е", base + "а", base + "у"})

    if "-" in base:
        variants.add(base.split("-")[0])

    if base == "санкт-петербург":
        variants.update({"петербург", "спб", "питер"})
    if base == "нижний новгород":
        variants.update({"нижнем новгороде", "нижнего новгорода", "нижнему новгороду"})
    if base == "ростов-на-дону":
        variants.update({"ростове-на-дону", "ростов"})

    return {v for v in variants if len(v) >= 3}
